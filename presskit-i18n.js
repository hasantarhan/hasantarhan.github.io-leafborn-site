  const englishText = new Map();
  const englishAttributes = new Map();

  function normalizeLanguage(value) {
    if (typeof value !== 'string') return null;
    const normalized = value.trim().toLowerCase().replace('_', '-');
    if (normalized === 'pt' || normalized.startsWith('pt-')) return 'pt-BR';
    if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN';
    const primaryLanguage = normalized.split('-')[0];
    return SUPPORTED_LANGUAGES.has(primaryLanguage) ? primaryLanguage : null;
  }

  function getStoredLanguage() {
    try {
      return normalizeLanguage(window.localStorage.getItem(STORAGE_KEY));
    } catch {
      return null;
    }
  }

  function getSystemLanguage() {
    const languages = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language];
    return normalizeLanguage(languages[0]) || 'en';
  }

  function rememberEnglishContent() {
    document.querySelectorAll('[data-i18n]').forEach((element) => {
      englishText.set(element, element.textContent);
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
      const [attribute] = element.dataset.i18nAttr.split(':');
      englishAttributes.set(element, element.getAttribute(attribute) || '');
    });
  }

  function applyLanguage(language) {
    const normalized = normalizeLanguage(language) || 'en';
    const dictionary = translations[normalized] || {};

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const translated = dictionary[element.dataset.i18n];
      element.textContent = translated !== undefined ? translated : englishText.get(element);
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
      const [attribute, key] = element.dataset.i18nAttr.split(':');
      const translated = dictionary[key];
      element.setAttribute(attribute, translated !== undefined ? translated : englishAttributes.get(element));
    });

    document.documentElement.lang = normalized;
    document.documentElement.dataset.language = normalized;
    const selector = document.getElementById('language-select');
    if (selector) selector.value = normalized;

    const languageOption = document.querySelector('.language-menu [data-language="' + normalized + '"]');
    const languageCode = document.querySelector('.language-current-code');
    if (languageOption && languageCode) languageCode.textContent = languageOption.querySelector('strong').textContent;
    document.querySelectorAll('.language-menu [data-language]').forEach((option) => {
      const isActive = option === languageOption;
      option.setAttribute('aria-selected', isActive ? 'true' : 'false');
      option.classList.toggle('is-active', isActive);
    });
  }

  function saveLanguage(language) {
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // The selected language still applies for this visit when storage is unavailable.
    }
  }

  rememberEnglishContent();

  const initialLanguage = getStoredLanguage() || getSystemLanguage();
  applyLanguage(initialLanguage);

  const selector = document.getElementById('language-select');
  if (selector) {
    selector.addEventListener('change', (event) => {
      const language = normalizeLanguage(event.target.value) || 'en';
      saveLanguage(language);
      applyLanguage(language);
    });
  }
